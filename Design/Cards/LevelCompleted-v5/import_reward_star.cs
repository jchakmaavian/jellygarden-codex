if (UnityEngine.Application.isPlaying) throw new System.InvalidOperationException("Import the star only in Edit Mode.");
const string path = "Assets/JellyGarden/Resources/RoyalGameplay/win-star.png";
UnityEditor.AssetDatabase.ImportAsset(path, UnityEditor.ImportAssetOptions.ForceSynchronousImport);
var importer = UnityEditor.AssetImporter.GetAtPath(path) as UnityEditor.TextureImporter;
if (importer == null) throw new System.InvalidOperationException("Reward star texture importer is missing.");
importer.textureType = UnityEditor.TextureImporterType.Sprite;
importer.spriteImportMode = UnityEditor.SpriteImportMode.Single;
importer.spritePixelsPerUnit = 100;
importer.mipmapEnabled = false;
importer.alphaIsTransparency = true;
importer.maxTextureSize = 1024;
importer.npotScale = UnityEditor.TextureImporterNPOTScale.None;
importer.textureCompression = UnityEditor.TextureImporterCompression.Uncompressed;
importer.filterMode = UnityEngine.FilterMode.Bilinear;
importer.wrapMode = UnityEngine.TextureWrapMode.Clamp;
var settings = new UnityEditor.TextureImporterSettings();
importer.ReadTextureSettings(settings);
settings.spriteMeshType = UnityEngine.SpriteMeshType.FullRect;
importer.SetTextureSettings(settings);
importer.SaveAndReimport();
var sprite = UnityEditor.AssetDatabase.LoadAssetAtPath<UnityEngine.Sprite>(path);
return new { imported = sprite != null, width = sprite ? sprite.texture.width : 0, height = sprite ? sprite.texture.height : 0 };
